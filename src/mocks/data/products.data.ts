function createVolumes(
  firstId: number,
  firstVolume: number,
  count: number,
  title: string,
  price: number,
  stock: number,
  filePrefix: string,
  onlyFirstCover: boolean = false,
): CatalogVolume[] {
  return Array.from({ length: count }, (_unused, index) => {
    const volumeNumber = firstVolume + index;
    const hasCover = filePrefix && (!onlyFirstCover || volumeNumber === 1);
    const coverUrl = hasCover
      ? `/images/products/${filePrefix}${String(volumeNumber).padStart(2, "0")}.jpg`
      : null;
    return {
      id: firstId + index,
      volumeNumber,
      title: `${title} เล่ม ${volumeNumber}`,
      coverUrl,
      images: coverUrl ? [coverUrl] : [],
      price,
      stock,
      weightGrams: 180,
      taxRate: 0,
      status: "IN_STOCK",
    };
  });
}

